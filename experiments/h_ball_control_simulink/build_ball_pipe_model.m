function [model_name, model_path] = build_ball_pipe_model(bp)
%BUILD_BALL_PIPE_MODEL Programmatically build the nonlinear Simulink model.
%
% Usage:
%   bp = ball_pipe_defaults;
%   build_ball_pipe_model(bp);
%   open_system('ball_pipe_nonlinear');

root = fileparts(mfilename('fullpath'));
addpath(root);

if nargin < 1
    bp = ball_pipe_defaults();
end

model_name = bp.meta.model_name;
model_path = fullfile(root, [model_name '.slx']);

assignin('base', 'bp', bp);
reference = timeseries(bp.reference.position, bp.reference.time);
reference.Name = 'commanded_ball_position';
assignin('base', 'bp_reference', reference);

if bdIsLoaded(model_name)
    close_system(model_name, 0);
end
new_system(model_name);

set_param(model_name, ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'ode4', ...
    'StopTime', num2str(bp.sim.stop_time, 16), ...
    'FixedStep', num2str(bp.sim.fixed_step, 16), ...
    'ZeroCrossControl', 'UseLocalSettings', ...
    'SaveTime', 'on', ...
    'TimeSaveName', 'tout', ...
    'ReturnWorkspaceOutputs', 'on');

% Main signal path blocks.
add_block('simulink/Sources/From Workspace', ...
    [model_name '/Ball position reference'], ...
    'VariableName', 'bp_reference', ...
    'Interpolate', 'off', ...
    'OutputAfterFinalValue', 'Holding final value', ...
    'Position', [30, 75, 165, 105]);

add_block('simulink/Signal Routing/Mux', ...
    [model_name '/Controller input mux'], ...
    'Inputs', '8', ...
    'Position', [220, 60, 225, 250]);

add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [model_name '/KF LQI and edge supervisor'], ...
    'FunctionName', 'sfun_lqg_edge_controller', ...
    'Parameters', 'bp', ...
    'Position', [270, 115, 440, 175]);

add_block('simulink/Signal Routing/Demux', ...
    [model_name '/Controller output demux'], ...
    'Outputs', '5', ...
    'Position', [475, 105, 480, 215]);

add_block('simulink/Discontinuities/Saturation', ...
    [model_name '/Command angle limit'], ...
    'UpperLimit', 'bp.actuator.max_angle', ...
    'LowerLimit', '-bp.actuator.max_angle', ...
    'Position', [520, 118, 640, 152]);

add_block('simulink/Discontinuities/Rate Limiter', ...
    [model_name '/Two-link pipe rate limit'], ...
    'RisingSlewLimit', 'bp.actuator.max_rate', ...
    'FallingSlewLimit', '-bp.actuator.max_rate', ...
    'Position', [660, 35, 785, 65]);

add_block('simulink/Continuous/Transport Delay', ...
    [model_name '/RS00 command and CAN delay'], ...
    'DelayTime', 'bp.actuator.delay', ...
    'InitialOutput', '0', ...
    'Position', [675, 118, 800, 152]);

add_block('simulink/Signal Routing/Mux', ...
    [model_name '/RS00 input mux'], ...
    'Inputs', '3', ...
    'Position', [820, 105, 825, 205]);

add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [model_name '/RS00 joint and pipe load'], ...
    'FunctionName', 'sfun_rs00_joint_actuator', ...
    'Parameters', 'bp', ...
    'Position', [865, 112, 1040, 178]);

add_block('simulink/Signal Routing/Demux', ...
    [model_name '/RS00 output demux'], ...
    'Outputs', '11', ...
    'Position', [1070, 70, 1075, 245]);

add_block('simulink/Continuous/Transport Delay', ...
    [model_name '/RS00 feedback CAN delay'], ...
    'DelayTime', 'bp.rs00.feedback_delay', ...
    'InitialOutput', '0', ...
    'Position', [1180, 72, 1310, 102]);

add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [model_name '/Nonlinear steel ball and PVC pipe'], ...
    'FunctionName', 'sfun_ball_pipe_plant', ...
    'Parameters', 'bp', ...
    'Position', [1125, 265, 1315, 315]);

add_block('simulink/Signal Routing/Demux', ...
    [model_name '/Plant output demux'], ...
    'Outputs', '10', ...
    'Position', [1355, 240, 1360, 375]);

add_block('simulink/Signal Routing/Mux', ...
    [model_name '/Vehicle IMU truth mux'], ...
    'Inputs', '2', ...
    'Position', [1410, 250, 1415, 320]);

add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [model_name '/MSPM0 vehicle IMU'], ...
    'FunctionName', 'sfun_vehicle_imu', ...
    'Parameters', 'bp', ...
    'Position', [1455, 260, 1605, 310]);

add_block('simulink/Signal Routing/Demux', ...
    [model_name '/Vehicle IMU output demux'], ...
    'Outputs', '2', ...
    'Position', [1640, 255, 1645, 325]);

add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [model_name '/Delayed noisy camera'], ...
    'FunctionName', 'sfun_pipe_camera', ...
    'Parameters', 'bp', ...
    'Position', [1120, 435, 1315, 485]);

add_block('simulink/Signal Routing/Demux', ...
    [model_name '/Camera output demux'], ...
    'Outputs', '3', ...
    'Position', [1355, 422, 1360, 505]);

% Connect the closed loop.
add_line(model_name, ...
    'Ball position reference/1', 'Controller input mux/1', 'autorouting', 'on');
add_line(model_name, ...
    'Controller input mux/1', 'KF LQI and edge supervisor/1', 'autorouting', 'on');
add_line(model_name, ...
    'KF LQI and edge supervisor/1', 'Controller output demux/1', 'autorouting', 'on');
add_line(model_name, ...
    'Controller output demux/1', 'Command angle limit/1', 'autorouting', 'on');
add_line(model_name, ...
    'Command angle limit/1', 'Two-link pipe rate limit/1', 'autorouting', 'on');
add_line(model_name, ...
    'Two-link pipe rate limit/1', 'RS00 command and CAN delay/1', 'autorouting', 'on');
add_line(model_name, ...
    'RS00 command and CAN delay/1', 'RS00 input mux/1', 'autorouting', 'on');
add_line(model_name, ...
    'RS00 input mux/1', 'RS00 joint and pipe load/1', 'autorouting', 'on');
add_line(model_name, ...
    'RS00 joint and pipe load/1', 'RS00 output demux/1', 'autorouting', 'on');
add_line(model_name, ...
    'RS00 output demux/1', ...
    'Nonlinear steel ball and PVC pipe/1', 'autorouting', 'on');
add_line(model_name, ...
    'RS00 output demux/9', 'RS00 feedback CAN delay/1', 'autorouting', 'on');
add_line(model_name, ...
    'RS00 feedback CAN delay/1', 'Controller input mux/5', 'autorouting', 'on');
add_line(model_name, ...
    'Nonlinear steel ball and PVC pipe/1', ...
    'Plant output demux/1', 'autorouting', 'on');
add_line(model_name, ...
    'Plant output demux/1', 'RS00 input mux/2', 'autorouting', 'on');
add_line(model_name, ...
    'Plant output demux/1', 'Delayed noisy camera/1', 'autorouting', 'on');
add_line(model_name, ...
    'Plant output demux/6', 'Controller input mux/6', 'autorouting', 'on');
add_line(model_name, ...
    'Plant output demux/6', 'RS00 input mux/3', 'autorouting', 'on');
add_line(model_name, ...
    'Plant output demux/7', 'Vehicle IMU truth mux/1', 'autorouting', 'on');
add_line(model_name, ...
    'Plant output demux/8', 'Vehicle IMU truth mux/2', 'autorouting', 'on');
add_line(model_name, ...
    'Vehicle IMU truth mux/1', 'MSPM0 vehicle IMU/1', 'autorouting', 'on');
add_line(model_name, ...
    'MSPM0 vehicle IMU/1', 'Vehicle IMU output demux/1', 'autorouting', 'on');
add_line(model_name, ...
    'Vehicle IMU output demux/1', 'Controller input mux/7', 'autorouting', 'on');
add_line(model_name, ...
    'Vehicle IMU output demux/2', 'Controller input mux/8', 'autorouting', 'on');
add_line(model_name, ...
    'Delayed noisy camera/1', 'Camera output demux/1', 'autorouting', 'on');
add_line(model_name, ...
    'Camera output demux/1', 'Controller input mux/2', 'autorouting', 'on');
add_line(model_name, ...
    'Camera output demux/2', 'Controller input mux/3', 'autorouting', 'on');
add_line(model_name, ...
    'Camera output demux/3', 'Controller input mux/4', 'autorouting', 'on');

% Scopes and workspace logging.
add_block('simulink/Signal Routing/Mux', ...
    [model_name '/Position scope mux'], ...
    'Inputs', '4', ...
    'Position', [570, 330, 575, 435]);
add_block('simulink/Sinks/Scope', ...
    [model_name '/Position scope'], ...
    'Position', [625, 352, 690, 413]);

add_line(model_name, ...
    'Ball position reference/1', 'Position scope mux/1', 'autorouting', 'on');
add_line(model_name, ...
    'Plant output demux/1', 'Position scope mux/2', 'autorouting', 'on');
add_line(model_name, ...
    'Controller output demux/2', 'Position scope mux/3', 'autorouting', 'on');
add_line(model_name, ...
    'Camera output demux/1', 'Position scope mux/4', 'autorouting', 'on');
add_line(model_name, ...
    'Position scope mux/1', 'Position scope/1', 'autorouting', 'on');

local_add_logger(model_name, 'Reference log', 'sim_reference', ...
    [model_name '/Ball position reference'], [30, 330, 150, 360]);
local_add_logger(model_name, 'Ball state log', 'sim_ball', ...
    [model_name '/Nonlinear steel ball and PVC pipe'], [1060, 525, 1180, 555]);
local_add_logger(model_name, 'RS00 state log', 'sim_rs00', ...
    [model_name '/RS00 joint and pipe load'], [830, 525, 950, 555]);
local_add_logger(model_name, 'Camera log', 'sim_camera', ...
    [model_name '/Delayed noisy camera'], [1240, 525, 1360, 555]);
local_add_logger(model_name, 'Controller log', 'sim_controller', ...
    [model_name '/KF LQI and edge supervisor'], [275, 525, 395, 555]);
local_add_logger(model_name, 'Vehicle IMU log', 'sim_vehicle_imu', ...
    [model_name '/MSPM0 vehicle IMU'], [1435, 525, 1555, 555]);

% Model annotations make the generated diagram self-explanatory.
annotation = Simulink.Annotation(model_name, sprintf([ ...
    'Nonlinear steel-ball / PVC-pipe model\\n' ...
    'Plant: rolling/sliding + Stribeck friction + rolling resistance + drag\\n' ...
    'Mechanism: RS00 crank + coupler + pipe rocker; nonlinear Jacobian/inertia\\n' ...
    'Actuator: motion mode + torque/current/speed/thermal limits\\n' ...
    'Vehicle: base acceleration + pitch + vertical vibration/shock\\n' ...
    'Sensor: Raspberry Pi camera/UART + MSPM0 IMU noise/delay\\n' ...
    'Controller: augmented KF/linear ESO + LQI + feedforward + edge recovery']));
annotation.Position = [40, 590, 700, 680];

save_system(model_name, model_path);
fprintf('Generated Simulink model: %s\n', model_path);

end


function local_add_logger(model_name, block_name, variable_name, source_path, position)
logger_path = [model_name '/' block_name];
add_block('simulink/Sinks/To Workspace', logger_path, ...
    'VariableName', variable_name, ...
    'SaveFormat', 'Timeseries', ...
    'Position', position);

source_name = source_path(numel(model_name)+2:end);
add_line(model_name, [source_name '/1'], [block_name '/1'], 'autorouting', 'on');

end
